// Builds site/js/life-expectancy.js from the WHO Global Health Observatory:
// life expectancy at birth (indicator WHOSIS_000001), by country and sex.
//
//   npm run life-expectancy
//
// The app never calls WHO. It ships this snapshot, so it still works offline
// and nothing about a visitor leaves their browser. Run this again when WHO
// publishes a new year, and commit the result.

import { writeFile } from 'node:fs/promises';

const API = 'https://ghoapi.azureedge.net/api';
const out = new URL('../site/js/life-expectancy.js', import.meta.url);
const SEX = { SEX_BTSX: 'both', SEX_MLE: 'male', SEX_FMLE: 'female' };

async function get(path) {
  const res = await fetch(`${API}/${path}`);
  if (!res.ok) throw new Error(`WHO answered ${res.status} for ${path}`);
  return (await res.json()).value;
}

const rows = await get(
  "WHOSIS_000001?$filter=SpatialDimType eq 'COUNTRY'&$select=SpatialDim,Dim1,TimeDim,NumericValue".replaceAll(' ', '%20'),
);
const names = new Map((await get('DIMENSION/COUNTRY/DimensionValues')).map((c) => [c.Code, c.Title]));

// The latest year each country has, for all three sexes.
const byCountry = new Map();
for (const r of rows) {
  const sex = SEX[r.Dim1];
  if (!sex || typeof r.NumericValue !== 'number') continue;
  const years = byCountry.get(r.SpatialDim) ?? new Map();
  const entry = years.get(r.TimeDim) ?? {};
  entry[sex] = Math.round(r.NumericValue * 10) / 10;
  years.set(r.TimeDim, entry);
  byCountry.set(r.SpatialDim, years);
}

const countries = [];
for (const [code, years] of byCountry) {
  const year = Math.max(...[...years].filter(([, e]) => e.both && e.male && e.female).map(([y]) => y));
  if (!Number.isFinite(year) || !names.has(code)) continue;
  const { both, male, female } = years.get(year);
  countries.push({ code, name: names.get(code), year, both, male, female });
}
countries.sort((a, z) => a.name.localeCompare(z.name, 'en'));

const body = `// Life expectancy at birth, in years, by country and sex.
// Generated by scripts/life-expectancy.mjs — do not edit by hand.
//
// Source: World Health Organization, Global Health Observatory, indicator
// WHOSIS_000001. Licensed CC BY-NC-SA 3.0 IGO.
// https://www.who.int/data/gho/data/indicators/indicator-details/GHO/life-expectancy-at-birth-(years)

export const SOURCE = {
  name: 'World Health Organization',
  url: 'https://www.who.int/data/gho/data/indicators/indicator-details/GHO/life-expectancy-at-birth-(years)',
  retrieved: '${new Date().toISOString().slice(0, 10)}',
};

export const COUNTRIES = ${JSON.stringify(countries, null, 0).replaceAll('},{', '},\n  {').replace('[{', '[\n  {').replace('}]', '},\n]')};
`;
await writeFile(out, body);
console.log(`Wrote ${countries.length} countries to ${out.pathname}`);
